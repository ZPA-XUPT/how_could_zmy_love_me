/* 跨平台 sleep(ms) */
#ifdef _WIN32
#include <windows.h>
static void delay_ms(int ms) { Sleep(ms); }
#else
#include <unistd.h>
static void delay_ms(int ms) { usleep(ms * 1000); }
#endif

void wait_for_enter(void) {
    char buf[8];
    /* 读取一行（直到回车） */
    if (fgets(buf, sizeof(buf), stdin) == NULL) {
        /* 输入结束或出错时，什么也不做 */
    }
}

/* 每调用一次 say，就输出一行文本，然后等玩家按一次回车 */
void say(const char *text) {
    printf("%s\n", text);
    fflush(stdout);
    wait_for_enter();
}

/* 读取玩家的数字选项，范围 [min, max] */
int ask_choice(int min, int max) {
    char buf[32];
    int choice;
    while (1) {
        printf("请输入 %d-%d：", min, max);
        fflush(stdout);
        if (!fgets(buf, sizeof(buf), stdin)) {
            continue;
        }
        choice = atoi(buf);
        if (choice >= min && choice <= max) {
            return choice;
        }
        printf("输入无效，请重新输入。\n");
    }
}

// 终端动画函数：在一段时间内显示进度条 + 旋转指针
void showTerminalAnimation(const char *message, int duration_ms) {
    const char spinner[] = "|/-\\";
    const int width = 30;  // 进度条宽度
    const int steps = 100; // 显示 100 步
    int sleep_ms = duration_ms / steps;
    if (sleep_ms <= 0) sleep_ms = 10;

    for (int step = 0; step <= steps; ++step) {
        int filled = (step * width) / steps;
        printf("\r[");
        for (int i = 0; i < filled; ++i) putchar('=');
        if (filled < width) putchar('>');
        for (int i = filled + 1; i < width; ++i) putchar(' ');
        int percent = (step * 100) / steps;
        char sp = spinner[step % (sizeof(spinner) - 1)];
        printf("] %3d%% %c %s", percent, sp, message);
        fflush(stdout);
        delay_ms(sleep_ms);
    }
    printf("\n");
}

void showDotPulseTransition2(const char *message, int duration_ms) {
    const int maxDots = 6;              // 最大点数（波峰）
    const int step_ms = 120;            // 每帧时长（毫秒）
    int steps = duration_ms / step_ms;  // 总帧数
    if (steps <= 0) steps = 1;

    for (int s = 0; s < steps; ++s) {
        int phase = s % (2 * maxDots);
        int dots = phase > maxDots ? 2 * maxDots - phase : phase; // 0..max..0
        printf("\r%s", message);
        for (int d = 0; d < dots; ++d) putchar('.');   // 实心点
        for (int d = dots; d < maxDots; ++d) putchar(' '); // 填充空格，防止残留
        fflush(stdout);
        delay_ms(step_ms);
    }
    printf("\n");
}

