/* 等待玩家按回车 */
void wait_for_enter() {
    char buf[8];
    printf("\n（按回车继续）\n");
    fgets(buf, sizeof(buf), stdin);
}

/* 读取玩家的数字选项，范围 [min, max] */
int ask_choice(int min, int max) {
    char buf[32];
    int choice;
    while (1) {
        printf("请输入 %d-%d：", min, max);
        if (!fgets(buf, sizeof(buf), stdin)) {
            continue;
        }
        choice = atoi(buf);
        if (choice >= min && choice <= max) {
            return choice;
        }
        printf("输入无效，请重新输入。\n");
    }
}

